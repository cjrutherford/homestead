const routeFixture = `Iface	Destination	Gateway 	Flags	RefCnt	Use	Metric	Mask		MTU	Window	IRTT
eth0	00000000	0101A8C0	0003	0	0	100	00000000	0	0	0
eth0	0001A8C0	00000000	0001	0	0	100	00FFFFFF	0	0	0
wlan0	00000000	0201A8C0	0003	0	0	600	00000000	0	0	0
`

func TestParseIPv4Routes(t *testing.T) {
	gateway, iface := parseIPv4Routes([]byte(routeFixture))
	if gateway != "192.168.1.1" || iface != "eth0" {
		t.Fatalf("got %q via %q, want 192.168.1.1 via eth0 (lowest metric)", gateway, iface)
	}
	gateway, iface = parseIPv4Routes([]byte("Iface	Destination	Gateway	Flags	RefCnt	Use	Metric	Mask	MTU	Window	IRTT\n"))
	if gateway != "" || iface != "" {
		t.Fatalf("got %q via %q, want empties", gateway, iface)
	}
}

func TestDecodeRouteAddress(t *testing.T) {
	for hex, want := range map[string]string{
		"0101A8C0": "192.168.1.1",
		"00000000": "0.0.0.0",
		"0100000A": "10.0.0.1",
	} {
		if got, err := decodeRouteAddress(hex); err != nil || got != want {
			t.Fatalf("decode %q = %q, %v; want %q", hex, got, err, want)
		}
	}
	for _, bad := range []string{"", "123", "ZZZZZZZZ", "0101A8C0FF"} {
		if _, err := decodeRouteAddress(bad); err == nil {
			t.Fatalf("decode %q accepted, want error", bad)
		}
	}
}

const resolvFixture = `# Generated by NetworkManager
search example.com
nameserver 192.168.1.1
nameserver 2001:4860:4860::8888
options edns0
nameserver not-an-ip
`

func TestParseResolvConf(t *testing.T) {
	got := parseResolvConf([]byte(resolvFixture))
	if len(got) != 2 || got[0] != "192.168.1.1" || got[1] != "2001:4860:4860::8888" {
		t.Fatalf("resolvers = %q", got)
	}
	if got := parseResolvConf([]byte("# empty\n")); len(got) != 0 {
		t.Fatalf("resolvers = %q, want none", got)
	}
}

func TestDiscoverNetworkLive(t *testing.T) {
	if runtime.GOOS != "linux" {
		t.Skip("Linux-only discovery")
	}
	got, err := DiscoverNetwork()
	if err != nil {
		t.Fatalf("DiscoverNetwork: %v", err)
	}
	if !got.HasInterface("lo") {
		t.Fatal("loopback interface missing")
	}
	for _, iface := range got.Interfaces {
		if iface.Name == "" {
			t.Fatalf("nameless interface: %+v", iface)
		}
		for _, addr := range iface.Addresses {
			if addr.IP == "" || addr.Network == "" {
				t.Fatalf("bad address %+v on %s", addr, iface.Name)
			}
		}
	}
	t.Logf("interfaces=%d gateway=%q via %q resolvers=%q",
		len(got.Interfaces), got.DefaultGateway, got.DefaultInterface, got.Resolvers)
}
