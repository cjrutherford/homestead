// HeadscaleImage pins the managed control plane (S114). Image updates
// arrive with the update flow (S190+); until then this constant is the
// version of record.
const HeadscaleImage = "headscale/headscale:0.29.4"

// Headscale stack layout: the optional managed control plane.
const (
	// HeadscaleStackName is the Compose project backing Headscale.
	HeadscaleStackName = "headscale"
	// HeadscaleService is the control-plane container.
	HeadscaleService = "headscale"
	// HeadscaleContainerName is the control-plane container name.
	HeadscaleContainerName = "homestead-headscale"
	// HeadscaleControlPort is the published control endpoint port.
	HeadscaleControlPort = 8080
)

// HeadscaleStack returns the control-plane stack value: fixed name,
// layout directory, the service, enabled.
func HeadscaleStack() Stack {
	return Stack{
		Name:     HeadscaleStackName,
		Dir:      DirFor(HeadscaleStackName),
		Services: []string{HeadscaleService},
		Enabled:  true,
	}
}

// checkHeadscaleStack rejects non-headscale stacks and empty dirs so
// deploy refuses misplacement instead of writing elsewhere.
func checkHeadscaleStack(stack Stack) error {
	if stack.Name != HeadscaleStackName {
		return fmt.Errorf("headscale: stack must be %q", HeadscaleStackName)
	}
	if stack.Dir == "" {
		return fmt.Errorf("headscale: stack dir must not be empty")
	}
	return nil
}

// headscaleConfig renders the minimal control-plane configuration: the
// public origin clients enrol against, loopback gRPC (management stays
// container-local until S117 drives it), SQLite state, and quiet logs.
// DNS stays at Headscale defaults — overlay DNS intent lands in S115,
// never smuggled through deployment.
func headscaleConfig(serverURL string) string {
	return `# Generated by Homestead (S114). Server URL is deployment input;
# everything else is the managed-profile default.
server_url: ` + serverURL + `
listen_addr: 0.0.0.0:8080
grpc_listen_addr: 127.0.0.1:5049
grpc_allow_insecure: false
database:
  type: sqlite
  sqlite:
    path: /var/lib/headscale/db.sqlite
log:
  format: text
  level: info
`
}

// WriteHeadscaleStack generates ordinary Compose artifacts under dir:
// compose.yaml, config directory with config.yaml, and the data
// directory. The result runs with vanilla `docker compose` — no
// Homestead at runtime (recovery rule, ADR-005). The server URL must be
// https: this profile exists for an independently reachable public
// control endpoint, and LAN-only http servers enrol through S112
// directly instead of a managed deployment.
func WriteHeadscaleStack(dir, serverURL string) error {
	var server overlay.HeadscaleServer = overlay.HeadscaleServer{URL: serverURL}
	if err := server.Validate(); err != nil {
		return err
	}
	if !strings.HasPrefix(serverURL, "https://") {
		return fmt.Errorf("headscale: managed profile needs an https control endpoint, got %q", serverURL)
	}
	for _, subdir := range []string{"config", "data"} {
		if err := os.MkdirAll(filepath.Join(dir, subdir), 0o755); err != nil {
			return fmt.Errorf("headscale: %s dir: %w", subdir, err)
		}
	}
	compose := `name: headscale
services:
  headscale:
    image: ` + HeadscaleImage + `
    container_name: ` + HeadscaleContainerName + `
    restart: unless-stopped
    ports:
      - "8080:8080"
    volumes:
      - ./config:/etc/headscale
      - ./data:/var/lib/headscale
    networks:
      - homestead-platform
networks:
  homestead-platform:
    external: true
`
	files := map[string]string{
		"compose.yaml":       compose,
		"config/config.yaml": headscaleConfig(serverURL),
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			return fmt.Errorf("headscale: write %s: %w", name, err)
		}
	}
	return nil
}

// HeadscaleDeployDefinition plans the control plane: the platform
// network, stack files, detached up, and a verify proving the server
// container runs. Idempotent throughout: existing networks
// short-circuit, files rewrite identically, up converges. User and key
// bootstrap ride in CreateUserDefinition and enrolment (S113/S117).
func HeadscaleDeployDefinition(stack Stack, serverURL string) (operation.Definition, error) {
	if err := checkHeadscaleStack(stack); err != nil {
		return operation.Definition{}, err
	}
	def := operation.Definition{Type: "headscale.deploy"}
	def.Steps = append(def.Steps, operation.StepDef{
		Name: "ensure-" + NetworkPlatform,
		Run: func(ctx context.Context) error {
			return ensureNetwork(ctx, NetworkSpec{Name: NetworkPlatform, Driver: "bridge"})
		},
	})
	def.Steps = append(def.Steps, operation.StepDef{
		Name: "write-stack",
		Run: func(ctx context.Context) error {
			return WriteHeadscaleStack(stack.Dir, serverURL)
		},
	})
	def.Steps = append(def.Steps, operation.StepDef{
		Name: "up",
		Run: func(ctx context.Context) error {
			return runCompose(ctx, stack, []string{"up", "-d"}, nil)
		},
	})
	def.Steps = append(def.Steps, operation.StepDef{
		Name: "verify",
		Run: func(ctx context.Context) error {
			return verifyService(ctx, stack, HeadscaleService)
		},
	})
	return def, nil
}

// CreateUserDefinition plans control-plane user bootstrap via the
// server CLI in its container, which reads the mounted configuration.
// Existing users converge to success (re-enrolment reruns the same
// definition), genuine failures abort.
func CreateUserDefinition(stack Stack, user string) (operation.Definition, error) {
	if err := checkHeadscaleStack(stack); err != nil {
		return operation.Definition{}, err
	}
	if !overlay.ValidHeadscaleUser(user) {
		return operation.Definition{}, fmt.Errorf("headscale: invalid user %q", user)
	}
	def := operation.Definition{Type: "headscale.user"}
	def.Steps = append(def.Steps, operation.StepDef{
		Name: "create-user",
		Run: func(ctx context.Context) error {
			_, err := execRun(ctx, "docker",
				"exec", HeadscaleContainerName,
				"headscale", "users", "create", user)
			if err != nil && strings.Contains(strings.ToLower(err.Error()), "already exists") {
				return nil
			}
			return err
		},
	})
	return def, nil
}
