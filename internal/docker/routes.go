package docker

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"homestead/internal/operation"
)

// RouteSnippetExt is the only suffix the reconciler manages. Stale
// cleanup removes exactly these files and nothing else, so hand-placed
// files in routes/ survive reconciliation.
const RouteSnippetExt = ".caddy"

// RouteFilename maps a validated hostname to its snippet file. Hostnames
// are lowercase DNS (S082), safe as filenames.
func RouteFilename(host Hostname) string {
	return string(host) + RouteSnippetExt
}

// RenderRoute renders one desired route as a Caddyfile snippet. TLS off
// pins an http:// site address (no auto-TLS); internal emits `tls
// internal`; auto relies on Caddy defaults. Exposure rides as a comment:
// the snippet serves every origin Caddy sees, and firewall planning
// (later slices) reconciles who may actually reach it. Health probing is
// emitted only when a path is set.
func RenderRoute(r Route) (string, error) {
	if err := r.Validate(); err != nil {
		return "", err
	}
	var site string
	switch r.TLS {
	case TLSOff:
		site = "http://" + string(r.Host)
	default:
		site = string(r.Host)
	}
	var body strings.Builder
	if r.TLS == TLSInternal {
		body.WriteString("\ttls internal\n")
	}
	upstream := fmt.Sprintf("%s:%d", r.Target.Host, r.Target.Port)
	if r.Health.Path == "" {
		fmt.Fprintf(&body, "\treverse_proxy %s\n", upstream)
	} else {
		fmt.Fprintf(&body, "\treverse_proxy %s {\n", upstream)
		fmt.Fprintf(&body, "\t\thealth_uri %s\n", r.Health.Path)
		if r.Health.IntervalSeconds != 0 {
			fmt.Fprintf(&body, "\t\thealth_interval %ds\n", r.Health.IntervalSeconds)
		}
		body.WriteString("\t}\n")
	}
	return fmt.Sprintf(`# Generated by Homestead (S083). Do not edit; reconcile overwrites.
# Exposure: %s. Upstream: %s.
%s {
%s}
`, r.Exposure, upstream, site, body.String()), nil
}

// ReconcileRoutes writes the desired route table into the stack routes
// directory and removes snippet files for hosts no longer desired. Writes
// are identical rewrites (idempotent); only *-managed suffix files are
// ever removed. It does not reload: callers chain ReloadProxy or run the
// ReconcileDefinition operation.
func ReconcileRoutes(dir string, set RouteSet) error {
	if err := set.Validate(); err != nil {
		return err
	}
	routesDir := filepath.Join(dir, "routes")
	if err := os.MkdirAll(routesDir, 0o755); err != nil {
		return fmt.Errorf("routes: dir: %w", err)
	}
	wanted := map[string]bool{}
	for _, r := range set.Sorted() {
		content, err := RenderRoute(r)
		if err != nil {
			return err
		}
		name := RouteFilename(r.Host)
		wanted[name] = true
		if err := os.WriteFile(filepath.Join(routesDir, name), []byte(content), 0o644); err != nil {
			return fmt.Errorf("routes: write %s: %w", name, err)
		}
	}
	entries, err := os.ReadDir(routesDir)
	if err != nil {
		return fmt.Errorf("routes: list: %w", err)
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), RouteSnippetExt) {
			continue
		}
		if wanted[entry.Name()] {
			continue
		}
		if err := os.Remove(filepath.Join(routesDir, entry.Name())); err != nil {
			return fmt.Errorf("routes: remove stale %s: %w", entry.Name(), err)
		}
	}
	return nil
}

// ReloadProxy asks the running proxy to adopt the reconciled snippets.
// Caddy validates before swapping, so a bad snippet keeps the old config
// and this returns the failure instead of serving it.
func ReloadProxy(ctx context.Context) error {
	if _, err := execRun(ctx, "docker",
		"exec", CaddyContainerName,
		"caddy", "reload",
		"--config", "/etc/caddy/Caddyfile",
		"--adapter", "caddyfile"); err != nil {
		return fmt.Errorf("reload proxy: %w", err)
	}
	return nil
}

// ReconcileDefinition plans route adoption: write the desired table,
// reload the proxy, and verify the proxy still runs. Idempotent
// throughout: files rewrite identically, stale snippets drop, reload
// converges, verify proves serving.
func ReconcileDefinition(stack Stack, set RouteSet) (operation.Definition, error) {
	if err := checkCaddyStack(stack); err != nil {
		return operation.Definition{}, err
	}
	if err := set.Validate(); err != nil {
		return operation.Definition{}, err
	}
	def := operation.Definition{Type: "caddy.reconcile"}
	def.Steps = append(def.Steps, operation.StepDef{
		Name: "write-routes",
		Run: func(ctx context.Context) error {
			return ReconcileRoutes(stack.Dir, set)
		},
	})
	def.Steps = append(def.Steps, operation.StepDef{
		Name: "reload",
		Run: func(ctx context.Context) error {
			return ReloadProxy(ctx)
		},
	})
	def.Steps = append(def.Steps, operation.StepDef{
		Name: "verify",
		Run: func(ctx context.Context) error {
			return verifyProxy(ctx, stack)
		},
	})
	return def, nil
}
