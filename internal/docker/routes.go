// RouteSnippetExt is the only suffix the reconciler manages. Stale
// cleanup removes exactly these files and nothing else, so hand-placed
// files in routes/ survive reconciliation.
const RouteSnippetExt = ".caddy"

// RouteFilename maps a validated hostname to its snippet file. Hostnames
// are lowercase DNS (S082), safe as filenames.
func RouteFilename(host Hostname) string {
	return string(host) + RouteSnippetExt
}

// RenderRoute renders one desired route as a Caddyfile snippet. TLS off
// pins an http:// site address (no auto-TLS); internal emits `tls
// internal`; auto relies on Caddy defaults. Exposure rides as a
// comment: the snippet serves every origin Caddy sees, and firewall
// planning (later slices) reconciles who may actually reach it. Health
// probing is emitted only when a path is set. Automatic mode on a
// private name is refused: no public CA can issue for it, so rendering
// would deploy a route Caddy can never bring up (S101) — use internal.
func RenderRoute(r Route) (string, error) { return renderRoute(r, nil, nil) }

// renderRoute is RenderRoute with an optional placed certificate for
// automatic-TLS routes (S278), and the dashboard's sign-in site
// certificate (ADR-047).
func renderRoute(r Route, cert, signIn *PlacedCert) (string, error) {
	if err := r.Validate(); err != nil {
		return "", err
	}
	if r.IsPath() {
		return "", fmt.Errorf("routes: %q is served at %s under the dashboard's names and has no site of its own", r.Host, r.Path)
	}
	if r.TLS == TLSAuto && IsPrivateName(r.Host) {
		return "", fmt.Errorf("routes: automatic TLS needs a public name, %q is private", r.Host)
	}
	var site string
	switch r.TLS {
	case TLSOff:
		site = "http://" + string(r.Host)
	default:
		site = string(r.Host)
	}
	for _, a := range r.ServedAliases() {
		if r.TLS == TLSOff {
			site += ", http://" + string(a)
		} else {
			site += ", " + string(a)
		}
	}
	var tlsLine, proxy strings.Builder
	if r.TLS == TLSInternal && cert == nil {
		tlsLine.WriteString("\ttls internal\n")
	}
	if cert != nil && r.usesPlacedCert() {
		fmt.Fprintf(&tlsLine, "\ttls %s/%s/%s/%s %s/%s/%s/%s\n",
			caddyRoutesDir, certsDirName, cert.Name, certChainFile,
			caddyRoutesDir, certsDirName, cert.Name, certKeyFile)
	}
	upstream := fmt.Sprintf("%s:%d", r.Target.Host, r.Target.Port)
	if r.Dashboard {
		upstream = "unix/" + DashboardSocketPath
		// The client address comes from the connection, never from what the
		// client sent (ADR-035): header_up replaces the headers, and
		// trusted_proxies stays unset. flush_interval -1 streams events.
		fmt.Fprintf(&proxy, "\treverse_proxy %s {\n\t\tflush_interval -1\n\t\theader_up X-Forwarded-For {http.request.remote.host}\n\t\theader_up X-Forwarded-Proto https\n\t\theader_up X-Forwarded-Host {http.request.host}\n\t}\n", upstream)
		if len(r.paths) > 0 {
			dash := proxy.String()
			proxy.Reset()
			proxy.WriteString(renderPathHandles(r.paths, false) + wrapHandle(dash))
		}
	} else if r.Health.Path == "" {
		fmt.Fprintf(&proxy, "\treverse_proxy %s\n", upstream)
	} else {
		fmt.Fprintf(&proxy, "\treverse_proxy %s {\n", upstream)
		fmt.Fprintf(&proxy, "\t\thealth_uri %s\n", r.Health.Path)
		if r.Health.IntervalSeconds != 0 {
			fmt.Fprintf(&proxy, "\t\thealth_interval %ds\n", r.Health.IntervalSeconds)
		}
		proxy.WriteString("\t}\n")
	}
	if r.CraftApp != "" {
		// The craft file path goes ahead of the upstream and inside the
		// exposure policy wrapper (ADR-032). header_up replaces anything
		// the client sent, so the daemon can trust the app and host.
		// X-Forwarded-Proto is set from the route's own TLS mode, never
		// from what the client sent.
		scheme := "https"
		if r.TLS == TLSOff {
			scheme = "http"
		}
		wrapped := fmt.Sprintf("\thandle %s* {\n\t\treverse_proxy unix/%s {\n\t\t\theader_up %s %s\n\t\t\theader_up %s %s\n\t\t\theader_up X-Forwarded-Proto %s\n\t\t}\n\t}\n\thandle {\n",
			CraftFilesPrefix, CraftSocketPath, CraftAppHeader, r.CraftApp, CraftHostHeader, r.Host, scheme)
		for _, line := range strings.Split(strings.TrimSuffix(proxy.String(), "\n"), "\n") {
			wrapped += "\t" + line + "\n"
		}
		wrapped += "\t}\n"
		proxy.Reset()
		proxy.WriteString(wrapped)
	}
	if r.Gate != nil {
		return fmt.Sprintf("# Generated by Homestead (S083). Do not edit; reconcile overwrites.\n# Exposure: %s. Upstream: %s. Gated by Authentik forward-auth (ADR-055).\n", r.Exposure, upstream) +
			renderGatedSites(r, tlsLine.String(), proxy.String(), tunnelProxy(r, upstream)) + renderSignInSite(r, signIn), nil
	}
	serving := tlsLine.String() + renderUpstream(dashboardPolicy(r), proxy.String())
	if r.redirectsToPublic() {
		serving = tlsLine.String() + fmt.Sprintf("\t# Single-origin sign-in (ADR-060): the local names redirect to the public name.\n\tredir https://%s{uri} 307\n", r.Tunnel[0])
	}
	return fmt.Sprintf(`# Generated by Homestead (S083). Do not edit; reconcile overwrites.
# Exposure: %s. Upstream: %s.
%s {
%s}
`, r.Exposure, upstream, site, serving) + renderTunnelEntry(r, upstream) + renderSignInSite(r, signIn), nil
}

// renderTunnelEntry is the site block for the route's tunnel names
// (ADR-037): plain HTTP on TunnelEntryPort, which the edge publishes on
// the host's loopback only, so the connector on this machine is the only
// client. Cloudflare terminated TLS; the client address is the one
// Cloudflare saw (Cf-Connecting-Ip), and an absent one leaves
// X-Forwarded-For empty, which the dashboard socket refuses.
func renderTunnelEntry(r Route, upstream string) string {
	if len(r.Tunnel) == 0 {
		return ""
	}
	sites := make([]string, 0, len(r.Tunnel))
	for _, n := range r.Tunnel {
		sites = append(sites, fmt.Sprintf("http://%s:%d", n, TunnelEntryPort))
	}
	body := tunnelProxy(r, upstream)
	if len(r.paths) > 0 {
		// Only published app paths answer on the public names; every
		// other /apps/ path answers 404 there (ADR-044 §3).
		body = renderPathHandles(r.paths, true) + wrapHandle(body)
	}
	return fmt.Sprintf(`
# Tunnel entry (ADR-037): public names the connector delivers on loopback.
%s {
%s}
`, strings.Join(sites, ", "), body)
}

// tunnelProxy is the reverse_proxy block of the tunnel entry: the client
// address is the one Cloudflare saw.
func tunnelProxy(r Route, upstream string) string {
	flush := ""
	if r.Dashboard {
		flush = "\t\tflush_interval -1\n"
	}
	return fmt.Sprintf("\treverse_proxy %s {\n%s\t\theader_up X-Forwarded-For {http.request.header.Cf-Connecting-Ip}\n\t\theader_up X-Forwarded-Proto https\n\t\theader_up X-Forwarded-Host {http.request.host}\n\t}\n", upstream, flush)
}

// indent puts every line of a block body one tab deeper.
func indent(body string) string {
	var b strings.Builder
	for _, line := range strings.Split(strings.TrimSuffix(body, "\n"), "\n") {
		b.WriteString("\t" + line + "\n")
	}
	return b.String()
}

// wrapHandle puts a block body in a catch-all handle, so it runs only
// when no app path handle matched.
func wrapHandle(body string) string {
	var b strings.Builder
	b.WriteString("\thandle {\n")
	for _, line := range strings.Split(strings.TrimSuffix(body, "\n"), "\n") {
		b.WriteString("\t" + line + "\n")
	}
	b.WriteString("\t}\n")
	return b.String()
}

// renderPathHandles renders the app paths served under the appliance's
// names (ADR-044): a redirect from the bare path to the path with its
// slash, each app's fixed redirects (Nextcloud's .well-known links), and
// one handle per path, stripping the prefix (uri strip_prefix) or
// keeping it as the package says. Any other /apps/ path answers 404, so
// the dashboard never answers for an app that is not there. On the
// tunnel entry only published paths are rendered; the client address
// is the one Cloudflare saw and the scheme is https.
func renderPathHandles(paths []Route, tunnel bool) string {
	var b strings.Builder
	b.WriteString("\t# Apps under the appliance's names (ADR-044).\n")
	for _, p := range paths {
		if tunnel && !p.Published {
			if p.ReadLinks {
				b.WriteString(renderReadLinkHandle(p))
			}
			continue
		}
		bare := strings.TrimSuffix(p.Path, "/")
		fmt.Fprintf(&b, "\tredir %s %s 308\n", bare, p.Path)
		for _, rd := range p.Redirects {
			fmt.Fprintf(&b, "\tredir %s %s%s 301\n", rd.From, p.Path, rd.To)
		}
		// One directive (handle) for every block, so Caddy sorts them by
		// path length and runs exactly one; handle_path would sort apart
		// from the /apps/ catch-all.
		fmt.Fprintf(&b, "\thandle %s* {\n", p.Path)
		b.WriteString(sharedOriginHeaders(p))
		if p.StripPrefix {
			fmt.Fprintf(&b, "\t\turi strip_prefix %s\n", bare)
		}
		up := pathUpstream(p, tunnel)
		if p.CraftApp == "" {
			b.WriteString(indent(up))
		} else {
			// A craft app's wrapper page and file path go to the daemon
			// (ADR-045). header_up replaces anything the client sent; the
			// host is the name the request came on, and the scheme is
			// https on both the dashboard site and the tunnel entry.
			fmt.Fprintf(&b, "\t\thandle %s* {\n\t\t\treverse_proxy unix/%s {\n\t\t\t\theader_up %s %s\n\t\t\t\theader_up %s {http.request.host}\n\t\t\t\theader_up %s %s\n\t\t\t\theader_up X-Forwarded-Proto https\n\t\t\t}\n\t\t}\n",
				CraftWrapperPrefix, CraftSocketPath, CraftAppHeader, p.CraftApp, CraftHostHeader, CraftPrefixHeader, bare)
			b.WriteString(indent(wrapHandle(up)))
		}
		b.WriteString("\t}\n")
	}
	fmt.Fprintf(&b, "\thandle %s* {\n\t\trespond 404\n\t}\n", AppsPrefix)
	return b.String()
}

// ReservedCookieNames are the cookies of the appliance's own sign-in on
// the shared origin (ADR-061 §4, S470): the dashboard session and CSRF
// cookies under both names, and Authentik's session and CSRF cookies. The
// edge never lets an app at a subpath see them, and never lets an app set
// them (cookie tossing).
var ReservedCookieNames = []string{
	"__Host-homestead_session", "__Host-homestead_csrf",
	"homestead_session", "homestead_csrf",
	"authentik_session", "authentik_csrf",
}

var reservedCookieAlt = strings.Join(ReservedCookieNames, "|")

// sharedOriginHeaders opens every app path handle on the shared origin.
// request_header removes the reserved cookies from the request after any
// forward-auth subrequest (it runs inside the app's handle); the matching
// header_down is in pathUpstream. The two header defaults use ? so an app
// package's own stricter value stays (S464). Quotes keep the pattern one
// Caddyfile token; there are no braces. Authentik itself at /apps/auth/
// owns authentik_session and authentik_csrf, so it keeps its cookies.
func sharedOriginHeaders(p Route) string {
	out := "\t\theader ?Content-Security-Policy \"frame-ancestors 'self'\"\n" +
		"\t\theader ?Referrer-Policy same-origin\n"
	if p.Path != SignInPath {
		out += "\t\trequest_header Cookie \"(?i)(^|;)[ ]*(" + reservedCookieAlt + ")=[^;]*\" \"\"\n"
	}
	return out
}

// ReadLinkPaths are the only two paths below an app's path that the
// read-link exposure plan opens on the public names (ADR-058): the raw
// route and the viewer, each followed by a 43 character token.
var ReadLinkPaths = []string{"_homestead/read/", "_homestead/view/"}

// ReadLinkTokenPattern is what the edge lets through as a token: one path
// segment of base64url characters, so no dot, slash or escape can reach the
// bridge. The bridge checks the exact length. It has no braces, which a
// Caddyfile reads as placeholders.
const ReadLinkTokenPattern = "[A-Za-z0-9_-]+"

// renderReadLinkHandle is the tunnel entry's handle for an app whose path
// is not published but whose read links are exposed. Only GET and HEAD of
// <path>_homestead/read/<token> and <path>_homestead/view/<token> reach
// the app; every other path below _homestead/ and every other app path
// answers 404 at the edge (the /apps/ catch-all). The client address is the
// one Cloudflare saw, replacing anything the client sent, which is what the
// bridge's -trusted-proxies expects.
func renderReadLinkHandle(p Route) string {
	var b strings.Builder
	b.WriteString("\t# Read links only (ADR-058): never the app itself.\n")
	fmt.Fprintf(&b, "\thandle %s_homestead/* {\n", p.Path)
	fmt.Fprintf(&b, "\t\t@readlink {\n\t\t\tmethod GET HEAD\n\t\t\tpath_regexp ^%s_homestead/(read|view)/%s$\n\t\t}\n", regexp.QuoteMeta(p.Path), ReadLinkTokenPattern)
	b.WriteString("\t\thandle @readlink {\n")
	b.WriteString(indent(sharedOriginHeaders(p)))
	b.WriteString(indent(indent(pathUpstream(p, true))))
	b.WriteString("\t\t}\n\t\thandle {\n\t\t\trespond 404\n\t\t}\n\t}\n")
	return b.String()
}

// pathUpstream is the reverse_proxy block of an app path.
func pathUpstream(p Route, tunnel bool) string {
	var up strings.Builder
	fmt.Fprintf(&up, "\treverse_proxy %s:%d {\n", p.Target.Host, p.Target.Port)
	if p.Health.Path != "" {
		fmt.Fprintf(&up, "\t\thealth_uri %s\n", p.Health.Path)
		if p.Health.IntervalSeconds != 0 {
			fmt.Fprintf(&up, "\t\thealth_interval %ds\n", p.Health.IntervalSeconds)
		}
	}
	if tunnel {
		up.WriteString("\t\theader_up X-Forwarded-For {http.request.header.Cf-Connecting-Ip}\n\t\theader_up X-Forwarded-Proto https\n")
	}
	up.WriteString("\t\theader_up X-Forwarded-Host {http.request.host}\n")
	if p.Path != SignInPath {
		fmt.Fprintf(&up, "\t\theader_down Set-Cookie \"(?i)^(%s)=.*\" \"\"\n", reservedCookieAlt)
	}
	up.WriteString("\t}\n")
	return up.String()
}

// ValidateRenderable checks a desired table end to end, including that
// every route renders (for example automatic TLS on a private name is
// refused), so callers can refuse before any file is written.
func ValidateRenderable(set RouteSet) error {
	if err := set.Validate(); err != nil {
		return err
	}
	for _, r := range withPaths(set.Routes) {
		if r.IsPath() {
			continue
		}
		if _, err := RenderRoute(r); err != nil {
			return err
		}
	}
	return nil
}

// RouteState is where the reconciler's ownership lives. Load returns the
// table the previous reconcile wrote and Save records the new one; a nil
// field means no ownership record, so nothing is ever removed as stale.
type RouteState struct {
	Load func() (RouteSet, error)
	Save func(RouteSet) error
	// Skip, when set, is asked inside the write step with the freshly
	// loaded record; true leaves the table untouched. It lets a caller
	// planned on an older snapshot stand down when the record changed
	// meanwhile (for example an owner-set dashboard name).
	Skip func(current RouteSet) bool
}

// ReconcileRoutes writes the desired route table into the stack routes
// directory. The reconciler owns exactly the hosts in prior (the table
// its previous run wrote): only those snippets are removed when no
// longer desired. Snippets it never wrote, such as those the exposure
// flow places or hand-placed files, are never removed. The returned
// undo restores every touched file, so a failed reload leaves disk
// matching the running config. It does not reload.
func ReconcileRoutes(dir string, set, prior RouteSet) (undo func() error, err error) {
	if err := ValidateRenderable(set); err != nil {
		return nil, err
	}
	routesDir := filepath.Join(dir, "routes")
	if err := os.MkdirAll(routesDir, 0o755); err != nil {
		return nil, fmt.Errorf("routes: dir: %w", err)
	}
	type saved struct {
		path    string
		content []byte
		existed bool
	}
	var log []saved
	remember := func(path string) error {
		for _, entry := range log {
			if entry.path == path {
				return nil
			}
		}
		content, err := os.ReadFile(path)
		switch {
		case err == nil:
			log = append(log, saved{path, content, true})
		case os.IsNotExist(err):
			log = append(log, saved{path: path})
		default:
			return fmt.Errorf("routes: read %s: %w", path, err)
		}
		return nil
	}
	undo = func() error {
		var first error
		for i := len(log) - 1; i >= 0; i-- {
			entry := log[i]
			var err error
			if entry.existed {
				err = os.WriteFile(entry.path, entry.content, 0o644)
			} else if rmErr := os.Remove(entry.path); rmErr != nil && !os.IsNotExist(rmErr) {
				err = rmErr
			}
			if err != nil && first == nil {
				first = fmt.Errorf("routes: rollback %s: %w", entry.path, err)
			}
		}
		return first
	}
	fail := func(cause error) (func() error, error) {
		if rbErr := undo(); rbErr != nil {
			cause = fmt.Errorf("%w (rollback also failed: %v)", cause, rbErr)
		}
		return nil, cause
	}
	wanted := map[string]bool{}
	for _, r := range withPaths(set.Sorted()) {
		if r.IsPath() {
			// Served inside the dashboard's site block (ADR-044).
			continue
		}
		content, err := RenderRouteIn(dir, r)
		if err != nil {
			return fail(err)
		}
		name := RouteFilename(r.Host)
		wanted[name] = true
		path := filepath.Join(routesDir, name)
		if err := remember(path); err != nil {
			return fail(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return fail(fmt.Errorf("routes: write %s: %w", name, err))
		}
	}
	for _, r := range prior.Routes {
		name := RouteFilename(r.Host)
		if wanted[name] {
			continue
		}
		path := filepath.Join(routesDir, name)
		if info, statErr := os.Stat(path); statErr == nil && info.IsDir() {
			continue
		}
		if err := remember(path); err != nil {
			return fail(err)
		}
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return fail(fmt.Errorf("routes: remove stale %s: %w", name, err))
		}
	}
	return undo, nil
}

// ReloadProxy asks the running proxy to adopt the reconciled snippets.
// Caddy validates before swapping, so a bad snippet keeps the old config
// and this returns the failure instead of serving it. The reload is
// forced: a re-issued certificate is rewritten in place under the same
// snippet, so the adapted config is identical and Caddy would otherwise
// skip the reload and keep serving the old certificate from memory.
func ReloadProxy(ctx context.Context) error {
	if _, err := execRun(ctx, "docker",
		"exec", CaddyContainerName,
		"caddy", "reload",
		"--config", "/etc/caddy/Caddyfile",
		"--adapter", "caddyfile",
		"--force"); err != nil {
		return fmt.Errorf("reload proxy: %w", err)
	}
	return nil
}

// ReconcileDefinition plans route adoption: write the desired table
// (recording it in state), reload the proxy, and verify the proxy still
// runs. Files and the recorded table roll back if the reload is
// refused, so disk and record keep matching the running config. Only
// hosts the previous reconcile wrote are ever removed.
func ReconcileDefinition(stack Stack, set RouteSet, state RouteState) (operation.Definition, error) {
	if err := checkCaddyStack(stack); err != nil {
		return operation.Definition{}, err
	}
	if err := ValidateRenderable(set); err != nil {
		return operation.Definition{}, err
	}
	var undo func() error
	var prior RouteSet
	def := operation.Definition{Type: "caddy.reconcile"}
	def.Steps = append(def.Steps, operation.StepDef{
		Name: "write-routes",
		Run: func(ctx context.Context) error {
			prior = RouteSet{}
			if state.Load != nil {
				loaded, err := state.Load()
				if err != nil {
					return err
				}
				prior = loaded
			}
			if state.Skip != nil && state.Skip(prior) {
				return nil
			}
			u, err := ReconcileRoutes(stack.Dir, set, prior)
			if err != nil {
				return err
			}
			undo = u
			if state.Save != nil {
				if err := state.Save(set); err != nil {
					if rbErr := undo(); rbErr != nil {
						return fmt.Errorf("%w (rollback also failed: %v)", err, rbErr)
					}
					return err
				}
			}
			return nil
		},
	})
	def.Steps = append(def.Steps, operation.StepDef{
		Name: "reload",
		Run: func(ctx context.Context) error {
			err := ReloadProxy(ctx)
			if err == nil {
				return nil
			}
			if undo != nil {
				if rbErr := undo(); rbErr != nil {
					err = fmt.Errorf("%w (rollback also failed: %v)", err, rbErr)
				}
			}
			if state.Save != nil {
				if saveErr := state.Save(prior); saveErr != nil {
					err = fmt.Errorf("%w (restoring route record failed: %v)", err, saveErr)
				}
			}
			return err
		},
	})
	def.Steps = append(def.Steps, operation.StepDef{
		Name: "verify",
		Run: func(ctx context.Context) error {
			if err := verifyProxy(ctx, stack); err != nil {
				return err
			}
			if err := verifyCraftMount(ctx, set); err != nil {
				return err
			}
			return verifyDashboardMount(ctx, set)
		},
	})
	return def, nil
}

// redirectsToPublic reports a published single-origin app's route (ADR-060):
// its local names redirect to its first public name while it has one.
func (r Route) redirectsToPublic() bool {
	return r.SingleOrigin && r.Gate == nil && !r.Dashboard && !r.IsPath() && len(r.Tunnel) > 0
}

// LANRedirect is the public address a published single-origin route's local
// names redirect to, and those names (ADR-060); empty when it does not.
func (r Route) LANRedirect() (to string, from []Hostname) {
	if !r.redirectsToPublic() {
		return "", nil
	}
	return "https://" + string(r.Tunnel[0]), r.Names()
}
