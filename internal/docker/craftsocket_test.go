func craftRoute(policy *Policy) Route {
	r := routeFor("gridcraft.lan", TLSInternal, ExposureLocal)
	r.Target = Target{Host: "gridcraft", Port: 8080}
	r.CraftApp = "gridcraft"
	r.Policy = policy
	return r
}

func TestRenderCraftRouteForwardsFilesAheadOfUpstream(t *testing.T) {
	got, err := RenderRoute(craftRoute(nil))
	if err != nil {
		t.Fatal(err)
	}
	want := `# Generated by Homestead (S083). Do not edit; reconcile overwrites.
# Exposure: local. Upstream: gridcraft:8080.
gridcraft.lan, gridcraft.local {
	tls internal
	handle /_homestead/files/* {
		reverse_proxy unix//run/homestead-craft/files.sock {
			header_up X-Homestead-Craft-App gridcraft
			header_up X-Homestead-Craft-Host gridcraft.lan
			header_up X-Forwarded-Proto https
		}
	}
	handle {
		reverse_proxy gridcraft:8080 {
			health_uri /healthz
			health_interval 30s
		}
	}
}
`
	if got != want {
		t.Fatalf("render:\n%s\nwant:\n%s", got, want)
	}
	if strings.Index(got, "_homestead/files") > strings.Index(got, "reverse_proxy gridcraft:8080") {
		t.Fatal("the file path must come before the upstream proxy")
	}
}

func TestRenderCraftRouteInsideExposurePolicy(t *testing.T) {
	policy := officePolicy()
	got, err := RenderRoute(craftRoute(policy))
	if err != nil {
		t.Fatal(err)
	}
	allowed := strings.Index(got, "handle @allowed {")
	files := strings.Index(got, "handle /_homestead/files/*")
	abort := strings.LastIndex(got, "abort")
	if allowed < 0 || files < allowed || abort < files {
		t.Fatalf("the craft file path must sit inside the policy's allowed handle:\n%s", got)
	}
}

