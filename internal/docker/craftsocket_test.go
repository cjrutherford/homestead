func TestCaddyStackMountsCraftSocketDirReadOnly(t *testing.T) {
	dir := t.TempDir()
	if err := WriteStack(dir); err != nil {
		t.Fatal(err)
	}
	compose, _ := os.ReadFile(filepath.Join(dir, "compose.yaml"))
	want := "- /run/homestead-craft:/run/homestead-craft:ro"
	if !strings.Contains(string(compose), want) {
		t.Fatalf("compose lacks %q:\n%s", want, compose)
	}
	if strings.Contains(string(compose), "/run/homestead:") || strings.Contains(string(compose), "homestead.sock") {
		t.Fatalf("the recovery socket directory must never be mounted:\n%s", compose)
	}
}

func stubInspect(t *testing.T, mounts string, inspectErr error) {
	t.Helper()
	old := execRun
	execRun = func(_ context.Context, name string, args ...string) (string, error) {
		joined := name + " " + strings.Join(args, " ")
		switch {
		case strings.Contains(joined, "inspect"):
			return mounts, inspectErr
		case strings.Contains(joined, "ps --format json"):
			return "{\"Service\":\"caddy\",\"State\":\"running\"}\n", nil
		}
		return "", nil
	}
	t.Cleanup(func() { execRun = old })
}

func runReconcile(t *testing.T, set RouteSet) operation.Operation {
	t.Helper()
	runner := openCaddyRunner(t)
	stack := routesStackIn(t)
	def, err := ReconcileDefinition(stack, set, RouteState{})
	if err != nil {
		t.Fatal(err)
	}
	op, err := runner.Start(context.Background(), def, "")
	if err != nil {
		t.Fatal(err)
	}
	done, err := runner.Wait(context.Background(), op.ID)
	if err != nil {
		t.Fatal(err)
	}
	return done
}

func TestReconcileDetectsMissingCraftMount(t *testing.T) {
	set := RouteSet{Routes: []Route{craftRoute(nil)}}
	// An edge deployed before ADR-032: no craft mount.
	stubInspect(t, `[{"Destination":"/etc/caddy/routes","RW":false}]`, nil)
	done := runReconcile(t, set)
	if done.Status != operation.StatusFailed {
		t.Fatalf("reconcile with a missing mount = %q, want failed", done.Status)
	}
	if !strings.Contains(done.Error, "redeploy the edge") {
		t.Fatalf("error does not say how to fix it: %q", done.Error)
	}
	// With the mount it passes.
	stubInspect(t, `[{"Destination":"/run/homestead-craft","RW":false}]`, nil)
	if done := runReconcile(t, set); done.Status != operation.StatusSucceeded {
		t.Fatalf("reconcile with the mount = %q (%s)", done.Status, done.Error)
	}
	// Without craft routes the mount is not required.
	stubInspect(t, `[]`, errors.New("must not be asked"))
	if done := runReconcile(t, routesSet()); done.Status != operation.StatusSucceeded {
		t.Fatalf("non-craft reconcile = %q (%s)", done.Status, done.Error)
	}
}

func TestCraftMountPresent(t *testing.T) {
	stubInspect(t, `[{"Destination":"/data"},{"Destination":"/run/homestead-craft"}]`, nil)
	if ok, err := CraftMountPresent(context.Background()); err != nil || !ok {
		t.Fatalf("present: %v %v", ok, err)
	}
	stubInspect(t, `[{"Destination":"/data"}]`, nil)
	if ok, _ := CraftMountPresent(context.Background()); ok {
		t.Fatal("absent mount reported present")
	}
	stubInspect(t, `not json`, nil)
	if _, err := CraftMountPresent(context.Background()); err == nil {
		t.Fatal("garbled inspect output accepted")
	}
}

