func TestManagementBaseline(t *testing.T) {
	set, err := ManagementBaseline(8080, fixtureNetwork())
	if err != nil {
		t.Fatalf("baseline: %v", err)
	}
	if len(set.Rules) != 5 {
		t.Fatalf("rules = %+v, want loopback pair + 2 accepts + public drop", set.Rules)
	}
	if set.Rules[0].Name != "management-loopback" || set.Rules[0].Priority != 50 {
		t.Fatalf("first = %+v, want loopback at 50", set.Rules[0])
	}
	if set.Rules[1].Source.CIDR != "::1/128" {
		t.Fatalf("second = %+v, want v6 loopback", set.Rules[1])
	}
	last := set.Rules[len(set.Rules)-1]
	if last.Name != "management-public-drop" || last.Action != ActionDrop || last.Source.CIDR != "" {
		t.Fatalf("last = %+v, want match-all public drop", last)
	}
	if _, err := ManagementBaseline(0, fixtureNetwork()); err == nil {
		t.Fatal("port 0 accepted, want error")
	}
}

func TestRenderExact(t *testing.T) {
	set := RuleSet{Rules: []Rule{
		{
			Name:       "mgmt-lan",
			Interfaces: []string{"eth0"},
			Source:     Source{Zone: ZoneLocal, CIDR: "192.168.1.0/24"},
			Service:    Service{Name: "management", Protocol: ProtocolTCP, Port: 8080},
			Action:     ActionAccept,
			Priority:   100,
		},
		{
			Name:     "mgmt-public-drop",
			Source:   Source{Zone: ZonePublic},
			Service:  Service{Name: "management", Protocol: ProtocolTCP, Port: 8080},
			Action:   ActionDrop,
			Priority: 900,
		},
		{
			Name:     "dns-lan",
			Source:   Source{Zone: ZoneLocal, CIDR: "10.0.0.0/8"},
			Service:  Service{Name: "dns", Protocol: ProtocolUDP, Port: 53},
			Action:   ActionAccept,
			Priority: 200,
		},
	}}
	got, err := Render(set)
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	want := `# Generated by homestead-server: do not edit. Homestead manages
# ONLY the "homestead" table below; all other tables are the
# administrator's (ADR-008).
table inet homestead {
    chain input {
        type filter hook input priority filter; policy accept;
        # mgmt-lan
        iifname "eth0" ip saddr 192.168.1.0/24 tcp dport 8080 accept comment "mgmt-lan"
        # dns-lan
        ip saddr 10.0.0.0/8 udp dport 53 accept comment "dns-lan"
        # mgmt-public-drop
        tcp dport 8080 drop comment "mgmt-public-drop"
    }
}
`
	if got != want {
		t.Fatalf("rendered:\n%s\nwant:\n%s", got, want)
	}
}

func TestRenderRejectsInvalid(t *testing.T) {
	if _, err := Render(RuleSet{}); err != nil {
		t.Fatalf("empty set: %v (valid: harmless empty table)", err)
	}
	bad := RuleSet{Rules: []Rule{{Name: "x", Action: ActionAccept}}}
	if _, err := Render(bad); err == nil {
		t.Fatal("invalid set rendered, want error")
	}
}

func TestRenderedTablePassesNFTCheck(t *testing.T) {
	nft := testtools.SkipUnlessTool(t, "nft")
	set, err := ManagementBaseline(8080, fixtureNetwork())
	if err != nil {
		t.Fatalf("baseline: %v", err)
	}
	script, err := Render(set)
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	path := filepath.Join(t.TempDir(), "homestead.nft")
	if err := os.WriteFile(path, []byte(script), 0o600); err != nil {
		t.Fatalf("write: %v", err)
	}
	out, err := exec.Command(nft, "--check", "--file", path).CombinedOutput()
	if err != nil {
		testtools.SkipOrFail(t, "nft", fmt.Sprintf("--check: %v: %s", err, strings.TrimSpace(string(out))))
	}
}
