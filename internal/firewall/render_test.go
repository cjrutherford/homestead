func fixtureNetwork() discover.Network {
	return discover.Network{Interfaces: []discover.Interface{
		{Name: "lo", Index: 1, MTU: 65536, Loopback: true,
			Addresses: []discover.Address{{IP: "127.0.0.1", Network: "127.0.0.0/8"}}},
		{Name: "eth0", Index: 2, MTU: 1500, Up: true, Multicast: true,
			Addresses: []discover.Address{
				{IP: "192.168.1.5", Network: "192.168.1.0/24"},
				{IP: "fe80::1", Network: "fe80::/64"},
			}},
		{Name: "wlan0", Index: 3, MTU: 1500, Up: true,
			Addresses: []discover.Address{{IP: "10.0.0.9", Network: "10.0.0.0/8"}}},
		{Name: "down0", Index: 4, MTU: 1500,
			Addresses: []discover.Address{{IP: "172.16.0.2", Network: "172.16.0.0/12"}}},
	}}
}

func TestLocalSubnets(t *testing.T) {
	got := LocalSubnets(fixtureNetwork())
	want := []string{"10.0.0.0/8", "192.168.1.0/24"}
	if len(got) != len(want) {
		t.Fatalf("subnets = %q, want %q", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("subnets = %q, want %q", got, want)
		}
	}
	dupes := fixtureNetwork()
	dupes.Interfaces = append(dupes.Interfaces, discover.Interface{
		Name: "eth1", Index: 5, MTU: 1500, Up: true,
		Addresses: []discover.Address{{IP: "192.168.1.6", Network: "192.168.1.0/24"}},
	})
	if got := LocalSubnets(dupes); len(got) != 2 {
		t.Fatalf("subnets = %q, want duplicates merged", got)
	}
}

func TestExpand(t *testing.T) {
	set, err := Expand([]ServicePolicy{{
		Service: Service{Name: "dashboard", Protocol: ProtocolTCP, Port: 8080},
		Sources: []Source{{Zone: ZoneLocal}, {Zone: ZonePublic, CIDR: "203.0.113.0/24"}},
	}}, fixtureNetwork())
	if err != nil {
		t.Fatalf("Expand: %v", err)
	}
	if len(set.Rules) != 3 {
		t.Fatalf("rules = %+v, want 3", set.Rules)
	}
	if set.Rules[0].Name != "dashboard-local-1" || set.Rules[0].Priority != 100 {
		t.Fatalf("first = %+v", set.Rules[0])
	}
	if set.Rules[1].Source.CIDR != "192.168.1.0/24" {
		t.Fatalf("second = %+v", set.Rules[1])
	}
	if set.Rules[2].Action != ActionAccept || set.Rules[2].Source.CIDR != "203.0.113.0/24" {
		t.Fatalf("third = %+v", set.Rules[2])
	}
}

