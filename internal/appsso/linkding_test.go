func realLinkding(t *testing.T) catalog.Manifest {
	t.Helper()
	entries, err := catalog.Load("../../catalog")
	if err != nil {
		t.Fatal(err)
	}
	m, err := entries.Get("linkding")
	if err != nil {
		t.Fatal(err)
	}
	if err := m.Validate(); err != nil {
		t.Fatalf("linkding manifest: %v", err)
	}
	// The data owner (33:33) makes the secret files a chown the daemon
	// does as root; tests run unprivileged, so drop it here.
	data := append([]catalog.DataPath(nil), m.Services[0].Data...)
	for i := range data {
		data[i].UID, data[i].GID = nil, nil
	}
	m.Services = append([]catalog.Service(nil), m.Services...)
	m.Services[0].Data = data
	return m
}

// TestLinkdingPlanAndApplyExistingInstall (S409): a Linkding installed
// before the manifest declared the client secret has the superuser
// supervisor only. Sign-in apply wires the new secret into the stack file
// and the supervisor script, the endpoints are built from Authentik's
// address, and the secret value is in no Compose, override or script file.
func TestLinkdingPlanAndApplyExistingInstall(t *testing.T) {
	stubDocker(t)
	m := realLinkding(t)
	dir := t.TempDir()
	old := m
	old.SSO.OIDC = nil
	old.Secrets = old.Secrets[:1]
	files, err := catalog.Generate(old, catalog.Generation{
		Services: []catalog.ServiceGeneration{{Service: "linkding"}}, RouteHosts: map[string]string{"linkding": "linkding.lan"}})
	if err != nil {
		t.Fatal(err)
	}
	app := &appSecrets{m: map[string]string{catalog.SecretStoreName("linkding", "superuser_password"): "su-pass-value"}}
	if err := catalog.WriteStack(dir, files, app); err != nil {
		t.Fatal(err)
	}
	script := filepath.Join(dir, catalog.EntrypointFile("linkding"))
	if b, _ := os.ReadFile(script); strings.Contains(string(b), "OIDC_RP_CLIENT_SECRET") {
		t.Fatal("old supervisor already exports the client secret")
	}
	if catalog.SecretConsumerWired(dir, m, "oidc_client_secret") {
		t.Fatal("old stack reads as wired")
	}
	rt, _, baselines := mealieRuntime(t, dir, app)
	in := Inputs{Manifest: m, Installed: true, AuthentikInstalled: true, Dashboard: dashboard, DashboardOK: true,
		StackNeedsSecret: true, Routes: AppRoutes(m, []docker.Route{route("linkding.lan", "linkding")})}
	plan, err := BuildPlan(in, true)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(strings.Join(plan.AppSettings, "\n"), "stack file is rewritten to deliver the sign-in secret") {
		t.Fatalf("plan does not say the stack is rewritten:\n%v", plan.AppSettings)
	}
	if len(plan.RedirectURIs) != 2 || plan.RedirectURIs[0] != "https://linkding.lan/oidc/callback/" ||
		plan.RedirectURIs[1] != "https://linkding.local/oidc/callback/" || plan.SignInURL != "https://linkding.lan/oidc/authenticate/" {
		t.Fatalf("redirects %v sign in %s", plan.RedirectURIs, plan.SignInURL)
	}
	ak := &fakeAuthentik{}
	def, err := Definition(rt, plan, m, dashboard, ak, "owner")
	if err != nil {
		t.Fatal(err)
	}
	for _, step := range def.Steps {
		if err := step.Run(context.Background()); err != nil {
			t.Fatalf("%s: %v", step.Name, err)
		}
	}
	value := app.m[catalog.SecretStoreName("linkding", "oidc_client_secret")]
	if value == "" || ak.secret != value {
		t.Fatalf("secret %q vs reconcile %q", value, ak.secret)
	}
	if *baselines == 0 {
		t.Fatal("drift not re-baselined after the stack file changed")
	}
	if fi, err := os.Stat(filepath.Join(dir, "secrets", "linkding_oidc_client_secret")); err != nil || fi.Mode().Perm() != 0o600 {
		t.Fatalf("secret file: %v", err)
	}
	compose, _ := os.ReadFile(filepath.Join(dir, "compose.yaml"))
	for _, w := range []string{"OIDC_RP_CLIENT_SECRET_FILE: /run/secrets/linkding_oidc_client_secret", "file: ./secrets/linkding_oidc_client_secret",
		"- linkding_oidc_client_secret", "LD_SUPERUSER_PASSWORD_FILE", "# Generated by Homestead"} {
		if !strings.Contains(string(compose), w) {
			t.Fatalf("compose lacks %q:\n%s", w, compose)
		}
	}
	sup, _ := os.ReadFile(script)
	for _, w := range []string{"export OIDC_RP_CLIENT_SECRET\n", "unset OIDC_RP_CLIENT_SECRET_FILE\n", "export LD_SUPERUSER_PASSWORD\n"} {
		if !strings.Contains(string(sup), w) {
			t.Fatalf("supervisor lacks %q:\n%s", w, sup)
		}
	}
	override, _ := os.ReadFile(filepath.Join(dir, catalog.OverrideFileName))
	for _, w := range []string{"LD_ENABLE_OIDC: \"True\"",
		"OIDC_OP_AUTHORIZATION_ENDPOINT: https://authentik.lan/application/o/authorize/",
		"OIDC_OP_TOKEN_ENDPOINT: https://authentik.lan/application/o/token/",
		"OIDC_OP_USER_ENDPOINT: https://authentik.lan/application/o/userinfo/",
		"OIDC_OP_JWKS_ENDPOINT: https://authentik.lan/application/o/homestead-linkding/jwks/",
		"OIDC_RP_CLIENT_ID: homestead-linkding", "OIDC_RP_SIGN_ALGO: RS256", "OIDC_USERNAME_CLAIM: preferred_username",
		"REQUESTS_CA_BUNDLE: /etc/homestead/ca/ca.crt"} {
		if !strings.Contains(string(override), w) {
			t.Fatalf("override lacks %q:\n%s", w, override)
		}
	}
	for name, body := range map[string][]byte{"compose": compose, "override": override, "supervisor": sup} {
		if strings.Contains(string(body), value) {
			t.Fatalf("secret value in %s", name)
		}
	}
	if !catalog.SecretConsumerWired(dir, m, "oidc_client_secret") {
		t.Fatal("not wired after apply")
	}
	if wrote, err := catalog.WireDeclaredSecret(dir, m, "oidc_client_secret"); err != nil || wrote {
		t.Fatalf("second wiring wrote=%v err=%v", wrote, err)
	}
	// A compose file that is wired but whose supervisor is the old one
	// reads as unwired and is repaired without touching compose.yaml.
	if err := os.WriteFile(script, []byte("#!/bin/sh\nexec \"$@\"\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	if catalog.SecretConsumerWired(dir, m, "oidc_client_secret") {
		t.Fatal("stale supervisor reads as wired")
	}
	if wrote, err := catalog.WireDeclaredSecret(dir, m, "oidc_client_secret"); err != nil || !wrote {
		t.Fatalf("repair wrote=%v err=%v", wrote, err)
	}
	if b, _ := os.ReadFile(script); !strings.Contains(string(b), "export OIDC_RP_CLIENT_SECRET\n") {
		t.Fatal("supervisor not repaired")
	}
}

// TestLinkdingTrustFollowsIssuer: requests treats REQUESTS_CA_BUNDLE as
// its whole trust store, so it is set only for the appliance's own issuer.
func TestLinkdingTrustFollowsIssuer(t *testing.T) {
	m := realLinkding(t)
	a := envOIDC{cfg: *m.SSO.OIDC.Env}
	if got := a.TrustEnvFor("https://authentik.lan/application/o/homestead-linkding/"); got["REQUESTS_CA_BUNDLE"] != CAFile {
		t.Fatalf("private issuer trust = %v", got)
	}
	if got := a.TrustEnvFor("https://auth.example.com/application/o/homestead-linkding/"); got != nil {
		t.Fatalf("public issuer trust = %v, want none", got)
	}
}

func TestAuthentikBase(t *testing.T) {
	for in, want := range map[string]string{
		"https://auth.example.com/application/o/homestead-x/": "https://auth.example.com",
		"https://host.lan/apps/authentik/application/o/x/":    "https://host.lan/apps/authentik",
		"https://plain.example/":                              "https://plain.example",
	} {
		if got := authentikBase(in); got != want {
			t.Fatalf("authentikBase(%q) = %q, want %q", in, got, want)
		}
	}
}
