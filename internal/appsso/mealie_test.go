func realMealie(t *testing.T) catalog.Manifest {
	t.Helper()
	entries, err := catalog.Load("../../catalog")
	if err != nil {
		t.Fatal(err)
	}
	m, err := entries.Get("mealie")
	if err != nil {
		t.Fatal(err)
	}
	if err := m.Validate(); err != nil {
		t.Fatalf("mealie manifest: %v", err)
	}
	// The data owner (911:911, S405) makes the secret file a chown the
	// daemon does as root; tests run unprivileged, so drop it here.
	data := append([]catalog.DataPath(nil), m.Services[0].Data...)
	for i := range data {
		data[i].UID, data[i].GID = nil, nil
	}
	m.Services = append([]catalog.Service(nil), m.Services...)
	m.Services[0].Data = data
	return m
}

// oldMealieStack writes the stack file an install made before the manifest
// declared its sign-in secret would have: no secrets at all.
func oldMealieStack(t *testing.T, dir string, m catalog.Manifest) string {
	t.Helper()
	old := m
	old.Secrets, old.FirstRun = nil, nil
	old.SSO.OIDC = nil
	files, err := catalog.Generate(old, catalog.Generation{
		Services: []catalog.ServiceGeneration{{Service: "mealie"}}, RouteHosts: map[string]string{"mealie": "mealie.lan"}})
	if err != nil {
		t.Fatal(err)
	}
	if err := catalog.WriteStack(dir, files, nil); err != nil {
		t.Fatal(err)
	}
	return files.ComposeYAML
}

func mealieRuntime(t *testing.T, dir string, app *appSecrets) (Runtime, *store.Store, *int) {
	t.Helper()
	st, err := store.Open(filepath.Join(t.TempDir(), "homestead.db"))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = st.Close() })
	baselines := new(int)
	return Runtime{Records: Records{DB: st.DB()}, Secrets: &memSecrets{m: map[string]string{}}, AppSecrets: app,
		StackDir: func(string) string { return dir },
		RootPEM: func() ([]byte, error) {
			return []byte("-----BEGIN CERTIFICATE-----\nroot\n-----END CERTIFICATE-----\n"), nil
		},
		Fingerprint: func(string, string) error { *baselines++; return nil },
	}, st, baselines
}

func TestMealiePlanAndApplyExistingInstall(t *testing.T) {
	stubDocker(t)
	m := realMealie(t)
	dir := t.TempDir()
	oldCompose := oldMealieStack(t, dir, m)
	if catalog.SecretConsumerWired(dir, m, "oidc_client_secret") {
		t.Fatal("old stack reads as wired")
	}
	if err := os.WriteFile(filepath.Join(dir, catalog.OverrideFileName), []byte("services:\n  mealie:\n    environment:\n      TZ: UTC\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	app := &appSecrets{m: map[string]string{}}
	rt, _, baselines := mealieRuntime(t, dir, app)
	in := Inputs{Manifest: m, Installed: true, AuthentikInstalled: true, Dashboard: dashboard, DashboardOK: true,
		StackNeedsSecret: true, Routes: AppRoutes(m, []docker.Route{route("mealie.lan", "mealie")})}
	plan, err := BuildPlan(in, true)
	if err != nil {
		t.Fatal(err)
	}
	text := strings.Join(plan.AppSettings, "\n")
	if !strings.Contains(text, "stack file is rewritten to deliver the sign-in secret") {
		t.Fatalf("plan does not say the stack is rewritten:\n%s", text)
	}
	in.StackNeedsSecret = false
	if p2, _ := BuildPlan(in, true); strings.Contains(strings.Join(p2.AppSettings, "\n"), "rewritten") {
		t.Fatal("wired stack plan mentions a rewrite")
	}
	want := []string{"https://mealie.lan/login", "https://mealie.lan/login?direct=1"}
	for _, w := range want {
		found := false
		for _, u := range plan.RedirectURIs {
			found = found || u == w
		}
		if !found {
			t.Fatalf("redirect %s missing: %v", w, plan.RedirectURIs)
		}
	}
	if plan.SignInURL != "https://mealie.lan/login" {
		t.Fatalf("sign in url %s", plan.SignInURL)
	}
	ak := &fakeAuthentik{}
	def, err := Definition(rt, plan, m, dashboard, ak, "owner")
	if err != nil {
		t.Fatal(err)
	}
	for _, step := range def.Steps {
		if err := step.Run(context.Background()); err != nil {
			t.Fatalf("%s: %v", step.Name, err)
		}
	}
	value := app.m[catalog.SecretStoreName("mealie", "oidc_client_secret")]
	if value == "" || ak.secret != value {
		t.Fatalf("secret %q vs reconcile %q", value, ak.secret)
	}
	if *baselines == 0 {
		t.Fatal("drift not re-baselined after the stack file changed")
	}
	if fi, err := os.Stat(filepath.Join(dir, "secrets", "mealie_oidc_client_secret")); err != nil || fi.Mode().Perm() != 0o600 {
		t.Fatalf("secret file: %v", err)
	}
	compose, _ := os.ReadFile(filepath.Join(dir, "compose.yaml"))
	for _, w := range []string{"OIDC_CLIENT_SECRET_FILE: /run/secrets/mealie_oidc_client_secret", "file: ./secrets/mealie_oidc_client_secret",
		"- mealie_oidc_client_secret", "BASE_URL: https://mealie.lan", "# Generated by Homestead", "container_name: "} {
		if !strings.Contains(string(compose), w) {
			t.Fatalf("compose lacks %q:\n%s", w, compose)
		}
	}
	if strings.Contains(string(compose), value) {
		t.Fatal("secret value in compose.yaml")
	}
	// Only additions: every line of the old file is still there.
	for _, line := range strings.Split(strings.TrimSpace(oldCompose), "\n") {
		if strings.HasPrefix(line, "secrets:") {
			continue
		}
		if !strings.Contains(string(compose), strings.TrimSpace(line)) {
			t.Fatalf("old line lost: %q", line)
		}
	}
	// A stack Homestead generates today reads as wired, and wiring twice is a no-op.
	if !catalog.SecretConsumerWired(dir, m, "oidc_client_secret") {
		t.Fatal("not wired after apply")
	}
	if wrote, err := catalog.WireDeclaredSecret(dir, m, "oidc_client_secret"); err != nil || wrote {
		t.Fatalf("second wiring wrote=%v err=%v", wrote, err)
	}
	override, _ := os.ReadFile(filepath.Join(dir, catalog.OverrideFileName))
	g := groupNames("mealie")
	for _, w := range []string{"TZ: UTC", "OIDC_AUTH_ENABLED: \"true\"", "OIDC_CLIENT_ID: homestead-mealie",
		"OIDC_CONFIGURATION_URL: https://authentik.lan/application/o/homestead-mealie/.well-known/openid-configuration",
		"OIDC_PROVIDER_NAME: Authentik", "OIDC_SIGNUP_ENABLED: \"true\"", "OIDC_AUTO_REDIRECT: \"false\"",
		"OIDC_REMEMBER_ME: \"true\"", "OIDC_GROUPS_CLAIM: groups", "OIDC_ADMIN_GROUP: " + g.Admins, "OIDC_USER_GROUP: " + g.Users,
		"OIDC_TLS_CACERTFILE: /etc/homestead/ca/ca.crt"} {
		if !strings.Contains(string(override), w) {
			t.Fatalf("override lacks %q:\n%s", w, override)
		}
	}
	if strings.Contains(string(override), "SSL_CERT_FILE") || strings.Contains(string(override), value) {
		t.Fatalf("override carries SSL_CERT_FILE or the secret:\n%s", override)
	}
}
