package catalog

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"gopkg.in/yaml.v3"
)

func composeManifest() Manifest {
	manifest := validManifest()
	manifest.Services = append(manifest.Services, Service{
		Name: "worker", Image: "jellyfin/worker:1.2.3", Exposes: "web",
	})
	return manifest
}

func composeGeneration() Generation {
	return Generation{
		Networks: []NetworkAttachment{
			{Name: "homestead-edge", External: true},
			{Name: "appnet"},
		},
		Services: []ServiceGeneration{
			{
				Service: "jellyfin",
				Ports:   []PortMapping{{Host: 8096, Container: 8096}},
				Volumes: []VolumeMapping{
					{Source: "/mnt/media/config", Target: "/config"},
					{Source: "/mnt/media/data", Target: "/data", ReadOnly: true},
				},
			},
			{Service: "worker"},
		},
	}
}

func TestGenerate(t *testing.T) {
	files, err := Generate(composeManifest(), composeGeneration())
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	for _, want := range []string{
		"Generated by Homestead (S153) from jellyfin 10.10.3",
		"name: jellyfin",
		"image: jellyfin/jellyfin:10.10.3",
		"container_name: jellyfin-jellyfin",
		"unless-stopped",
		"8096:8096",
		"source: /mnt/media/config",
		"target: /data",
		"read_only: true",
		"homestead-edge:",
		"external: true",
		"container_name: jellyfin-worker",
	} {
		if !strings.Contains(files.ComposeYAML, want) {
			t.Fatalf("missing %q:\n%s", want, files.ComposeYAML)
		}
	}
	if files.Stack.Name != "jellyfin" || len(files.Stack.Services) != 2 {
		t.Fatalf("stack = %+v", files.Stack)
	}
	if err := files.Stack.Validate(); err != nil {
		t.Fatalf("stack: %v", err)
	}
	// The document parses back as Compose.
	var parsed map[string]any
	if err := yaml.Unmarshal([]byte(files.ComposeYAML), &parsed); err != nil {
		t.Fatalf("parse: %v", err)
	}
	services, ok := parsed["services"].(map[string]any)
	if !ok || len(services) != 2 {
		t.Fatalf("services = %v", parsed["services"])
	}
	dir := t.TempDir()
	stackDir := filepath.Join(dir, "jellyfin")
	if err := WriteStack(stackDir, files); err != nil {
		t.Fatalf("WriteStack: %v", err)
	}
	written, err := os.ReadFile(filepath.Join(stackDir, "compose.yaml"))
	if err != nil {
		t.Fatalf("read: %v", err)
	}
	if string(written) != files.ComposeYAML {
		t.Fatal("written document differs")
	}
}

func TestGenerateValidation(t *testing.T) {
	manifest := composeManifest()
	generation := composeGeneration()
	generation.Services[0].Ports = []PortMapping{{Host: 0, Container: 80}}
	if _, err := Generate(manifest, generation); err == nil {
		t.Fatal("generated bad ports")
	}
	generation = composeGeneration()
	generation.Services = append(generation.Services, ServiceGeneration{Service: "ghost"})
	if _, err := Generate(manifest, generation); err == nil {
		t.Fatal("generated unknown service")
	}
	generation = composeGeneration()
	generation.Services[0].Volumes = []VolumeMapping{{Source: "relative", Target: "/x"}}
	if _, err := Generate(manifest, generation); err == nil {
		t.Fatal("generated relative source")
	}
	generation = composeGeneration()
	generation.Networks = []NetworkAttachment{{Name: "homestead-edge", External: true}, {Name: "homestead-edge"}}
	if _, err := Generate(manifest, generation); err == nil {
		t.Fatal("generated duplicate network")
	}
	bad := manifest
	bad.Name = "Bad!"
	if _, err := Generate(bad, composeGeneration()); err == nil {
		t.Fatal("generated bad manifest")
	}
	if _, err := Generate(manifest, Generation{Services: []ServiceGeneration{{Service: "jellyfin", Ports: []PortMapping{{Host: 1, Container: 1}, {Host: 1, Container: 2}}}}}); err == nil {
		t.Fatal("generated duplicate host ports")
	}
}

func TestGenerateCommand(t *testing.T) {
	manifest := composeManifest()
	manifest.Services[1].Command = []string{"worker", "--foreground"}
	files, err := Generate(manifest, composeGeneration())
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if !strings.Contains(files.ComposeYAML, "command:\n") || !strings.Contains(files.ComposeYAML, "- worker") {
		t.Fatalf("missing command:\n%s", files.ComposeYAML)
	}
	// Services without commands render none.
	lines := strings.Split(files.ComposeYAML, "\n")
	commands := 0
	for _, line := range lines {
		if strings.TrimSpace(line) == "command:" {
			commands++
		}
	}
	if commands != 1 {
		t.Fatalf("commands = %d, want 1", commands)
	}
	broken := manifest
	broken.Services[1].Command = []string{""}
	if _, err := Generate(broken, composeGeneration()); err == nil {
		t.Fatal("empty command argument accepted")
	}
}
