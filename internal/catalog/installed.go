package catalog

import (
	"fmt"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"
	"homestead/internal/store"
)

// Installed reports whether a package already has a stack: generated
// files recorded in the store or a compose.yaml on disk. Either
// signal counts, so a half-removed stack never reads as free.
func Installed(st *store.Store, name, dir string) (bool, error) {
	stacks, err := InstalledStacks(st)
	if err != nil {
		return false, err
	}
	for _, stack := range stacks {
		if stack == name {
			return true, nil
		}
	}
	if _, err := os.Stat(filepath.Join(dir, "compose.yaml")); err == nil {
		return true, nil
	} else if !os.IsNotExist(err) {
		return false, fmt.Errorf("catalog: inspect stack: %w", err)
	}
	return false, nil
}

// RefuseInstalled returns a clear error when the package is already
// installed: installing again would rewrite compose.yaml, provision
// empty directories, and recreate containers on new bind mounts,
// orphaning the data they held. Owners configure or update instead.
// When a manifest is supplied and the existing stack lacks bind mounts
// for declared paths (installed before S276), the error points at the
// S277 migration. Recorded generated bytes stay authoritative: drift
// restore rewrites exactly what install recorded, never regenerates.
func RefuseInstalled(st *store.Store, name, dir string, manifest *Manifest) error {
	installed, err := Installed(st, name, dir)
	if err != nil {
		return err
	}
	if !installed {
		return nil
	}
	if manifest != nil && !hasDeclaredBinds(dir, *manifest) {
		return fmt.Errorf("catalog: %q is already installed with its data outside mounted storage (installed before S276); reinstalling would orphan that data — use the S277 data migration, then update", name)
	}
	return fmt.Errorf("catalog: %q is already installed; use configure or update instead of installing again", name)
}

// hasDeclaredBinds reports whether the stack's compose file mounts
// every persistent declared path. An unreadable file reads as not
// migrated: refusing with migration guidance beats guessing.
func hasDeclaredBinds(dir string, manifest Manifest) bool {
	raw, err := os.ReadFile(filepath.Join(dir, "compose.yaml"))
	if err != nil {
		return false
	}
	var doc struct {
		Services map[string]struct {
			Volumes []struct {
				Type   string `yaml:"type"`
				Target string `yaml:"target"`
			} `yaml:"volumes"`
		} `yaml:"services"`
	}
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return false
	}
	for _, service := range manifest.Services {
		bound := map[string]bool{}
		for _, volume := range doc.Services[service.Name].Volumes {
			if volume.Type == "bind" {
				bound[volume.Target] = true
			}
		}
		for _, data := range service.Data {
			if !data.Ephemeral && !bound[data.Target] {
				return false
			}
		}
	}
	return true
}
